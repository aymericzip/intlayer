import type { Locale } from '@intlayer/types/allLocales';
import type { AiProviders } from '@intlayer/types/config';
import type { KeyPath } from '@intlayer/types/keyPath';
import { z } from 'zod/mini';
import {
  dateTimeSchema,
  isJSONObject,
  paginationQueryShape,
  repeatableQueryValueSchema,
  typedStringSchema,
  typedValueSchema,
} from './common';
import {
  defineRoute,
  defineRouteGroup,
  type RouteBodyInput,
  type RouteQuerystring,
} from './defineRoute';
import {
  type PaginatedResponse,
  paginatedResponseSchema,
  type ResponseData,
  responseDataSchema,
} from './responseData';
import { tagSchema } from './tag';

/**
 * AI settings sent by a client. Provider-specific options (from the AI SDKs)
 * pass through untouched, so the value is only checked to be an object;
 * `@intlayer/ai`'s `AIOptions` is asserted assignable in the backend.
 */
export type AIOptions = {
  provider?: `${AiProviders}`;
  model?: string;
  temperature?: number;
  baseURL?: string;
  /** Own provider key; omitted to use the project or Intlayer key. */
  apiKey?: string;
  applicationContext?: string;
  dataSerialization?: 'json' | 'toon';
};

export const aiOptionsSchema = typedValueSchema<AIOptions>(isJSONObject);

/** Chat message exchanged with the assistants. */
export const chatCompletionRequestMessageSchema = z.object({
  role: z.enum(['system', 'user', 'assistant']),
  content: z.string(),
  /** ISO date-time, parsed to a `Date`. */
  timestamp: z.optional(
    z.pipe(
      z.string(),
      z.transform((value) => new Date(value))
    )
  ),
});

const localeSchema = typedStringSchema<Locale>();
const tokenUsedShape = { tokenUsed: z.number() };

/** Text result of an AI step (translation, audit, query). */
const fileContentResultSchema = z.object({
  fileContent: z.string(),
  ...tokenUsedShape,
});

/** Tag fields rewritten by the tag audit (parsed from the model's JSON). */
const tagAuditResultSchema = z.object({
  fileContent: z.looseObject({
    key: z.optional(z.string()),
    name: z.optional(z.string()),
    description: z.optional(z.string()),
    instructions: z.optional(z.string()),
  }),
  ...tokenUsedShape,
});

const metadataResultSchema = z.object({
  fileContent: z.object({
    title: z.string(),
    description: z.string(),
    tags: z.array(z.string()),
  }),
  ...tokenUsedShape,
});

/** JSON document translated by the AI. */
const jsonContentSchema = typedValueSchema<Record<string, unknown>>();

const tokenUsageSchema = z.object({
  inputTokens: z.number(),
  outputTokens: z.number(),
  totalTokens: z.number(),
});

/** Message stored in a discussion. */
export const discussionMessageSchema = z.object({
  role: z.enum(['user', 'assistant', 'system']),
  content: z.string(),
  relatedFiles: z.optional(z.array(z.string())),
  timestamp: dateTimeSchema,
});

/** Saved AI discussion (doc assistant or dashboard chat). */
export const discussionSchema = z.looseObject({
  id: z.string(),
  /** Generated by the client before the discussion is saved. */
  discussionId: z.string(),
  messages: z.optional(z.array(discussionMessageSchema)),
  numberOfMessages: z.number(),
  userId: z.optional(z.string()),
  projectId: z.optional(z.string()),
  organizationId: z.optional(z.string()),
  title: z.optional(z.string()),
  type: z.optional(z.enum(['doc', 'dashboard'])),
  isArchived: z.boolean(),
  aiModel: z.optional(z.string()),
  tokenUsage: z.optional(tokenUsageSchema),
  createdAt: dateTimeSchema,
  updatedAt: dateTimeSchema,
});

/** Token usage of the project's dashboard discussions, per model. */
export const aiStatsSchema = z.object({
  projectId: z.string(),
  generatedAt: z.number(),
  totalDiscussions: z.number(),
  totalInputTokens: z.number(),
  totalOutputTokens: z.number(),
  totalTokens: z.number(),
  modelUsage: z.array(
    z.object({
      aiModel: z.string(),
      discussionCount: z.number(),
      totalInputTokens: z.number(),
      totalOutputTokens: z.number(),
      totalTokens: z.number(),
    })
  ),
});

const aiOptionsShape = { aiOptions: z.optional(aiOptionsSchema) };
const tagsKeysShape = { tagsKeys: z.optional(z.array(z.string())) };
const conversationSchema = z.object({
  messages: z.array(chatCompletionRequestMessageSchema),
  discussionId: z.string(),
});

/** REST contract of the `/api/ai` routes. */
export const aiContract = defineRouteGroup({
  prefix: '/api/ai',
  tag: 'AI',
  routes: {
    customQuery: defineRoute({
      method: 'POST',
      path: '/',
      summary: 'Run a custom prompt',
      schemas: {
        body: z.looseObject({
          ...aiOptionsShape,
          ...tagsKeysShape,
          /** AI SDK model messages. */
          messages: typedValueSchema<unknown[]>(Array.isArray),
          system: z.optional(z.unknown()),
          applicationContext: z.optional(z.string()),
        }),
        response: { 200: responseDataSchema(fileContentResultSchema) },
      },
    }),
    translateJSON: defineRoute({
      method: 'POST',
      path: '/translate/json',
      summary: 'Translate a JSON document into a locale',
      schemas: {
        body: z.object({
          ...aiOptionsShape,
          ...tagsKeysShape,
          entryFileContent: jsonContentSchema,
          presetOutputContent: jsonContentSchema,
          dictionaryDescription: z.optional(z.string()),
          entryLocale: localeSchema,
          outputLocale: localeSchema,
          mode: z.enum(['complete', 'review']),
          applicationContext: z.optional(z.string()),
        }),
        response: {
          200: responseDataSchema(
            z.object({ fileContent: jsonContentSchema, ...tokenUsedShape })
          ),
        },
      },
    }),
    auditContentDeclaration: defineRoute({
      method: 'POST',
      path: '/audit/dictionary',
      summary: 'Audit and complete a content declaration file',
      schemas: {
        body: z.object({
          ...aiOptionsShape,
          ...tagsKeysShape,
          locales: z.array(localeSchema),
          defaultLocale: localeSchema,
          fileContent: z.string(),
          filePath: z.optional(z.string()),
        }),
        response: { 200: responseDataSchema(metadataResultSchema) },
      },
    }),
    auditContentDeclarationField: defineRoute({
      method: 'POST',
      path: '/audit/dictionary/field',
      summary: 'Audit a single field of a content declaration',
      schemas: {
        body: z.object({
          ...aiOptionsShape,
          ...tagsKeysShape,
          locales: z.array(localeSchema),
          fileContent: z.string(),
          filePath: z.optional(z.string()),
          keyPath: z.array(typedValueSchema<KeyPath>()),
        }),
        response: { 200: responseDataSchema(fileContentResultSchema) },
      },
    }),
    auditContentDeclarationMetadata: defineRoute({
      method: 'POST',
      path: '/audit/dictionary/metadata',
      summary: 'Suggest title, description and tags of a dictionary',
      schemas: {
        body: z.object({ ...aiOptionsShape, fileContent: z.string() }),
        response: { 200: responseDataSchema(metadataResultSchema) },
      },
    }),
    auditTag: defineRoute({
      method: 'POST',
      path: '/audit/tag',
      summary: 'Improve the instructions of a tag',
      schemas: {
        body: z.object({ ...aiOptionsShape, tag: tagSchema }),
        response: { 200: responseDataSchema(tagAuditResultSchema) },
      },
    }),
    ask: defineRoute({
      method: 'POST',
      path: '/ask',
      summary: 'Ask the documentation assistant (server-sent events stream)',
      schemas: { body: conversationSchema },
    }),
    chat: defineRoute({
      method: 'POST',
      path: '/chat',
      summary: 'Chat with the dashboard assistant (server-sent events stream)',
      schemas: { body: conversationSchema },
    }),
    autocomplete: defineRoute({
      method: 'POST',
      path: '/autocomplete',
      summary: 'Autocomplete a text being written',
      schemas: {
        body: z.object({
          ...aiOptionsShape,
          text: z.string(),
          contextBefore: z.optional(z.string()),
          currentLine: z.optional(z.string()),
          contextAfter: z.optional(z.string()),
        }),
        response: {
          200: responseDataSchema(z.object({ autocompletion: z.string() })),
        },
      },
    }),
    getDiscussions: defineRoute({
      method: 'GET',
      path: '/discussions',
      summary: 'List AI discussions (own ones, all for admins)',
      schemas: {
        querystring: z.looseObject({
          ...paginationQueryShape,
          includeMessages: z.optional(z.enum(['true', 'false'])),
          ids: z.optional(repeatableQueryValueSchema),
          userId: z.optional(z.string()),
          userIds: z.optional(repeatableQueryValueSchema),
          discussionId: z.optional(z.string()),
          search: z.optional(z.string()),
          isArchived: z.optional(z.enum(['true', 'false'])),
          sortBy: z.optional(z.string()),
          sortOrder: z.optional(z.string()),
          fetchAll: z.optional(z.enum(['true', 'false'])),
        }),
        response: { 200: paginatedResponseSchema(discussionSchema) },
      },
    }),
    getAIStats: defineRoute({
      method: 'GET',
      path: '/stats',
      summary: 'AI token usage of the selected project',
      schemas: {
        response: { 200: responseDataSchema(aiStatsSchema) },
      },
    }),
  },
});

/** Route definitions of the `/api/ai` group, by name. */
export type AIRoutes = (typeof aiContract)['routes'];

/**
 * Chat message as built by clients: `timestamp` may be a `Date` (serialized
 * to an ISO string on the wire) or already a string.
 */
export type ChatCompletionRequestMessage = Omit<
  z.output<typeof chatCompletionRequestMessageSchema>,
  'timestamp'
> & { timestamp?: Date | string };
export type DiscussionAPI = z.output<typeof discussionSchema>;
export type AIStats = z.output<typeof aiStatsSchema>;

export type CustomQueryBody = RouteBodyInput<AIRoutes['customQuery']>;
export type CustomQueryResult = ResponseData<
  z.output<typeof fileContentResultSchema>
>;
export type TranslateJSONBody = RouteBodyInput<AIRoutes['translateJSON']>;
export type TranslateJSONResult = ResponseData<{
  fileContent: Record<string, unknown>;
  tokenUsed: number;
}>;
export type AuditContentDeclarationBody = RouteBodyInput<
  AIRoutes['auditContentDeclaration']
>;
export type AuditContentDeclarationResult = ResponseData<
  z.output<typeof metadataResultSchema>
>;
export type AuditContentDeclarationFieldBody = RouteBodyInput<
  AIRoutes['auditContentDeclarationField']
>;
export type AuditContentDeclarationFieldResult = ResponseData<
  z.output<typeof fileContentResultSchema>
>;
export type AuditContentDeclarationMetadataBody = RouteBodyInput<
  AIRoutes['auditContentDeclarationMetadata']
>;
export type AuditContentDeclarationMetadataResult = ResponseData<
  z.output<typeof metadataResultSchema>
>;
export type AuditTagBody = RouteBodyInput<AIRoutes['auditTag']>;
export type AuditTagResultData = z.output<typeof tagAuditResultSchema>;
export type AuditTagResult = ResponseData<AuditTagResultData>;
export type AskDocQuestionBody = RouteBodyInput<AIRoutes['ask']>;
/** Final payload of the documentation assistant stream. */
export type AskDocQuestionResult = ResponseData<{
  response: string;
  relatedFiles: string[];
}>;
export type ChatBody = RouteBodyInput<AIRoutes['chat']>;
/** Final payload of the dashboard assistant stream. */
export type ChatResult = ResponseData<{
  response: string;
  tokenUsage?: z.output<typeof tokenUsageSchema>;
  aiModel?: string;
}>;
export type AutocompleteBody = RouteBodyInput<AIRoutes['autocomplete']>;
export type AutocompleteResponse = ResponseData<{ autocompletion: string }>;
export type GetDiscussionsParams = RouteQuerystring<AIRoutes['getDiscussions']>;
export type GetDiscussionsResult = PaginatedResponse<DiscussionAPI>;
export type GetAIStatsResult = ResponseData<AIStats>;
