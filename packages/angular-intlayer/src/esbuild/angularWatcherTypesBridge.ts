import {
  type FSWatcher,
  mkdirSync,
  readdirSync,
  readFileSync,
  watch,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, normalize, sep } from 'node:path';

/** Batch of changed paths, as `@angular/build`'s watcher yields it. */
export type ChangedFilesLike = {
  added: Set<string>;
  modified: Set<string>;
  removed: Set<string>;
  readonly all: string[];
};

/** Watcher returned by `@angular/build`'s `createWatcher`. */
export type AngularWatcher = AsyncIterableIterator<ChangedFilesLike> & {
  add: (paths: string | readonly string[]) => void;
  remove: (paths: string | readonly string[]) => void;
  close: () => Promise<void>;
};

/** Exports of `@angular/build/src/tools/esbuild/watcher.js` the bridge uses. */
export type AngularWatcherModule = {
  createWatcher: (options?: unknown) => AngularWatcher;
  ChangedFiles: new () => ChangedFilesLike;
};

/** Module running `ng serve` / `ng build --watch` rebuild loops. */
const BUILD_ACTION_MODULE_SUFFIX = [
  '@angular',
  'build',
  'src',
  'builders',
  'application',
  'build-action.js',
].join(sep);

/** Marks a watcher module already wrapped, so repeated setups wrap it once. */
const WRAPPED_MARKER = Symbol.for('intlayer.angular.watcherWrapped');

/** Delay letting a burst of declaration writes settle into one rebuild. */
const SETTLE_DELAY_MS = 50;

/** Name of the script whose rewrite makes TypeScript re-check every file. */
export const TYPES_REVISION_FILE_NAME = 'angular-types-revision.d.ts';

/** Generated declaration files: absolute path → contents. */
export type FileContents = Map<string, string>;

/**
 * Reads the declaration files of `directories`. A missing directory counts as
 * empty.
 */
export const readFileContents = (directories: string[]): FileContents => {
  const fileContents: FileContents = new Map();

  for (const directory of directories) {
    let fileNames: string[];

    try {
      fileNames = readdirSync(directory);
    } catch {
      continue;
    }

    for (const fileName of fileNames) {
      if (!fileName.endsWith('.ts') || fileName === TYPES_REVISION_FILE_NAME) {
        continue;
      }

      const filePath = normalize(join(directory, fileName));

      try {
        fileContents.set(filePath, readFileSync(filePath, 'utf-8'));
      } catch {
        // Removed between the listing and the read: reported as removed.
      }
    }
  }

  return fileContents;
};

/**
 * Files added, modified or removed between two snapshots. Comparing contents
 * rather than times keeps an identical rewrite from triggering a rebuild.
 */
export const diffFileContents = (
  previousContents: FileContents,
  currentContents: FileContents,
  changedFiles: ChangedFilesLike
): ChangedFilesLike => {
  for (const [filePath, contents] of currentContents) {
    const previous = previousContents.get(filePath);

    if (previous === undefined) changedFiles.added.add(filePath);
    else if (previous !== contents) changedFiles.modified.add(filePath);
  }

  for (const filePath of previousContents.keys()) {
    if (!currentContents.has(filePath)) changedFiles.removed.add(filePath);
  }

  return changedFiles;
};

/**
 * Contents of the revision script. It has no import or export, so TypeScript
 * treats it as affecting the global scope: rewriting it re-checks every file.
 */
export const getTypesRevisionContents = (revision: number): string =>
  [
    '// Generated by angular-intlayer. Rewritten when the dictionary types',
    '// change, so the Angular dev server re-checks every template.',
    // A declaration rather than a comment: TypeScript ignores comments when
    // deciding whether a file changed in a way that affects other files.
    `interface IntlayerAngularTypesRevision { revision: ${revision} }`,
    '',
  ].join('\n');

/**
 * Wraps an Angular watcher so it also yields the batches `subscribe` reports.
 *
 * The rebuild loop awaits one `next()` at a time: a pending call of the
 * original watcher is kept across calls, so no change it reports is lost when
 * an injected batch is returned first.
 */
export const mergeInjectedChanges = (
  angularWatcher: AngularWatcher,
  subscribe: (listener: (changedFiles: ChangedFilesLike) => void) => () => void
): AngularWatcher => {
  let pendingNext: Promise<IteratorResult<ChangedFilesLike>> | undefined;
  let queuedChanges: ChangedFilesLike | undefined;
  let wakeUp: (() => void) | undefined;

  const unsubscribe = subscribe((changedFiles) => {
    if (queuedChanges) {
      // Not consumed yet: fold the new batch into the queued one.
      changedFiles.added.forEach((path) => queuedChanges!.added.add(path));
      changedFiles.modified.forEach((path) =>
        queuedChanges!.modified.add(path)
      );
      changedFiles.removed.forEach((path) => queuedChanges!.removed.add(path));
    } else {
      queuedChanges = changedFiles;
    }

    wakeUp?.();
  });

  const bridgedWatcher: AngularWatcher = {
    [Symbol.asyncIterator]: () => bridgedWatcher,

    next: async () => {
      if (!queuedChanges) {
        pendingNext ??= angularWatcher.next();

        await Promise.race([
          pendingNext,
          new Promise<void>((resolve) => {
            wakeUp = resolve;
          }),
        ]);
        wakeUp = undefined;
      }

      if (queuedChanges) {
        const changedFiles = queuedChanges;
        queuedChanges = undefined;

        return { value: changedFiles, done: false };
      }

      const result = await pendingNext!;
      pendingNext = undefined;

      return result;
    },

    add: (paths) => angularWatcher.add(paths),
    remove: (paths) => angularWatcher.remove(paths),

    close: async () => {
      unsubscribe();
      await angularWatcher.close();
    },
  };

  return bridgedWatcher;
};

/**
 * Watches `directories` and reports each settled batch of changed
 * declarations, one listener per running Angular watcher.
 */
const createTypesChangeSource = (
  directories: string[],
  revisionFilePath: string,
  ChangedFiles: AngularWatcherModule['ChangedFiles']
) => {
  let revision = 0;
  mkdirSync(dirname(revisionFilePath), { recursive: true });
  writeFileSync(revisionFilePath, getTypesRevisionContents(revision));

  const listeners = new Set<(changedFiles: ChangedFilesLike) => void>();
  let fileContents = readFileContents(directories);
  let settleTimeout: ReturnType<typeof setTimeout> | undefined;
  let directoryWatchers: FSWatcher[] = [];

  const emitChanges = () => {
    const currentContents = readFileContents(directories);
    const changedFiles = diffFileContents(
      fileContents,
      currentContents,
      new ChangedFiles()
    );
    fileContents = currentContents;

    if (changedFiles.all.length === 0) return;

    // A dictionary type reaches components through module augmentation, not an
    // import, so the type-checker would keep each template's diagnostics. A
    // changed global script is the one change that re-checks every file.
    revision += 1;
    writeFileSync(revisionFilePath, getTypesRevisionContents(revision));
    changedFiles.modified.add(revisionFilePath);

    for (const listener of listeners) listener(changedFiles);
  };

  const scheduleEmit = () => {
    clearTimeout(settleTimeout);
    settleTimeout = setTimeout(emitChanges, SETTLE_DELAY_MS);
    settleTimeout.unref?.();
  };

  const startWatching = () => {
    directoryWatchers = directories.flatMap((directory) => {
      try {
        const directoryWatcher = watch(
          directory,
          { persistent: false },
          scheduleEmit
        );
        // Unhandled, a watcher error would crash the dev server: losing the
        // bridge only brings back the restart this works around.
        directoryWatcher.on('error', () => directoryWatcher.close());

        return [directoryWatcher];
      } catch {
        return [];
      }
    });
  };

  return (listener: (changedFiles: ChangedFilesLike) => void) => {
    if (listeners.size === 0) startWatching();
    listeners.add(listener);

    // Include writes between the initial snapshot and watcher subscription,
    // including events missed while the native watcher starts.
    scheduleEmit();

    return () => {
      listeners.delete(listener);

      if (listeners.size > 0) return;

      for (const directoryWatcher of directoryWatchers)
        directoryWatcher.close();
      directoryWatchers = [];
      clearTimeout(settleTimeout);
    };
  };
};

/**
 * `@angular/build` watcher modules of the builders loaded in this process.
 * Located from the module cache rather than resolved, so the wrap hits the
 * copy the running builder uses even when several are installed.
 */
const getAngularWatcherModules = (): AngularWatcherModule[] => {
  const require = createRequire(import.meta.url);

  return Object.keys(require.cache)
    .filter((modulePath) => modulePath.endsWith(BUILD_ACTION_MODULE_SUFFIX))
    .flatMap((buildActionPath) => {
      try {
        return [
          require(
            join(dirname(buildActionPath), '../../tools/esbuild/watcher.js')
          ) as AngularWatcherModule,
        ];
      } catch {
        return [];
      }
    })
    .filter(
      (watcherModule) =>
        typeof watcherModule?.createWatcher === 'function' &&
        typeof watcherModule.ChangedFiles === 'function'
    );
};

/**
 * Reports the declarations Intlayer rewrites under a dot-directory to the
 * Angular dev server's watcher.
 *
 * That watcher ignores `<workspace>/**\/.*\/**`, so a rewritten
 * `.intlayer/types` file is never reported and the TypeScript cache keeps the
 * stale declaration: a key added to a dictionary fails template type-checking
 * until `ng serve` restarts. Wrapping `createWatcher` — read by the builder
 * only once the first build is done, after plugin setup — makes it yield the
 * changed declarations too, so Angular rebuilds and re-reads them itself.
 *
 * @param directories - Absolute directories holding the generated declarations.
 * @param revisionDirectory - Directory, covered by the tsconfig `include`, that
 * receives the revision script (the module augmentation one).
 * @returns Whether a loaded Angular watcher module was wrapped.
 */
export const bridgeTypesToAngularWatcher = (
  directories: string[],
  revisionDirectory: string
): boolean => {
  const watcherModules = getAngularWatcherModules();

  for (const watcherModule of watcherModules) {
    const wrappableModule = watcherModule as AngularWatcherModule &
      Record<symbol, true>;

    if (wrappableModule[WRAPPED_MARKER]) continue;

    const originalCreateWatcher = watcherModule.createWatcher;
    const subscribe = createTypesChangeSource(
      directories,
      normalize(join(revisionDirectory, TYPES_REVISION_FILE_NAME)),
      watcherModule.ChangedFiles
    );

    watcherModule.createWatcher = (options) =>
      mergeInjectedChanges(originalCreateWatcher(options), subscribe);

    wrappableModule[WRAPPED_MARKER] = true;
  }

  return watcherModules.length > 0;
};
