import { describe, expect, it } from 'vitest';
import {
  convertMessage,
  evaluateMessagePreview,
  extractVariableNames,
} from './converterUtils';

describe('Message Converter Utilities', () => {
  describe('convertMessage', () => {
    it('should convert ICU simple interpolation to i18next and Vue', () => {
      const input = 'Hello {name}!';
      const toI18next = convertMessage(input, 'icu', 'i18next');
      expect(toI18next.success).toBe(true);
      expect(toI18next.output).toBe('Hello {{name}}!');

      const toVue = convertMessage(input, 'icu', 'vue-i18n');
      expect(toVue.success).toBe(true);
      expect(toVue.output).toBe('Hello {name}!');
    });

    it('should convert ICU plural to Vue pipe syntax', () => {
      const input =
        '{count, plural, =0 {No items} one {# item} other {# items}}';
      const toVue = convertMessage(input, 'icu', 'vue-i18n');
      expect(toVue.success).toBe(true);
      expect(toVue.output).toContain('No items');
      expect(toVue.output).toContain('{count} item');
      expect(toVue.output).toContain('{count} items');
    });

    it('should convert Vue pipe syntax to ICU plural', () => {
      const input = 'No apples | One apple | {count} apples';
      const toIcu = convertMessage(input, 'vue-i18n', 'icu');
      expect(toIcu.success).toBe(true);
      expect(toIcu.output).toContain('plural');
      expect(toIcu.output).toContain('No apples');
    });

    it('should convert ICU select to i18next and Intlayer content declaration using gender/select helper', () => {
      const input =
        '{gender, select, male {He liked your photo} female {She liked your photo} other {They liked your photo}}';
      const toIntlayer = convertMessage(input, 'icu', 'intlayer');
      expect(toIntlayer.success).toBe(true);
      expect(toIntlayer.contentDeclaration).toContain(
        "key: 'converted-message'"
      );
      expect(toIntlayer.contentDeclaration).toContain('gender({');
      expect(toIntlayer.contentDeclaration).toContain(
        "male: 'He liked your photo'"
      );
    });

    it('should remove __intlayer_icu_var and other internal metadata from Intlayer result', () => {
      const input =
        'You finished {rank, selectordinal, one {#st} two {#nd} few {#rd} other {#th}} place!';
      const toIntlayer = convertMessage(input, 'icu', 'intlayer');
      expect(toIntlayer.success).toBe(true);
      expect(toIntlayer.output).not.toContain('__intlayer_icu_var');
      expect(toIntlayer.output).not.toContain('__intlayer_icu_ordinal');
      expect(toIntlayer.contentDeclaration).not.toContain('__intlayer_icu_var');
      expect(toIntlayer.contentDeclaration).not.toContain(
        '__intlayer_icu_ordinal'
      );
    });

    it('should remove autogenerated tags property from HTML nodes and keep only nodeType and html', () => {
      const input =
        'Read our <a href="/terms">Terms of Service</a> or visit <strong>{siteName}</strong>.';
      const toIntlayer = convertMessage(input, 'icu', 'intlayer');
      expect(toIntlayer.success).toBe(true);
      expect(toIntlayer.output).not.toContain('"tags"');
      expect(toIntlayer.contentDeclaration).toContain(
        'html(\'Read our <a href="/terms">Terms of Service</a> or visit <strong>{{siteName}}</strong>.\')'
      );
    });

    it('should generate content declaration with enu helper for ordinals', () => {
      const input =
        'You finished {rank, selectordinal, one {#st} two {#nd} few {#rd} other {#th}} place!';
      const toIntlayer = convertMessage(input, 'icu', 'intlayer');
      expect(toIntlayer.success).toBe(true);
      expect(toIntlayer.contentDeclaration).toContain('enu({');
      expect(toIntlayer.contentDeclaration).toContain("one: '{{rank}}st'");
      expect(toIntlayer.contentDeclaration).toContain("fallback: '{{rank}}th'");
    });

    it('should handle multi-key JSON dictionary input', () => {
      const input = JSON.stringify({
        greeting: 'Hello {name}!',
        total: 'You have {count} items',
      });
      const toI18next = convertMessage(input, 'icu', 'i18next');
      expect(toI18next.success).toBe(true);
      const parsed = JSON.parse(toI18next.output);
      expect(parsed.greeting).toBe('Hello {{name}}!');
      expect(parsed.total).toBe('You have {{count}} items');
    });

    it('should generate content declaration and json declaration for Intlayer target', () => {
      const input = '{count, plural, one {# item} other {# items}}';
      const result = convertMessage(input, 'icu', 'intlayer');
      expect(result.success).toBe(true);
      expect(result.contentDeclaration).toContain(
        "import { type Dictionary, plural } from 'intlayer';"
      );
      expect(result.contentDeclaration).toContain("key: 'converted-message'");

      expect(result.contentJsonDeclaration).toBeDefined();
      const parsedJson = JSON.parse(result.contentJsonDeclaration!);
      expect(parsedJson.$schema).toBe('https://intlayer.org/schema.json');
      expect(parsedJson.key).toBe('converted-message');
      expect(parsedJson.content.nodeType).toBe('plural');
    });

    it('should handle empty input gracefully', () => {
      const result = convertMessage('', 'icu', 'i18next');
      expect(result.success).toBe(true);
      expect(result.output).toBe('');
    });
  });

  describe('extractVariableNames', () => {
    it('should extract variables from ICU message', () => {
      const input =
        '{count, plural, one {# item for {user}} other {# items for {user}}}';
      const vars = extractVariableNames(input);
      expect(vars).toContain('count');
      expect(vars).toContain('user');
    });

    it('should extract variables from i18next double-braces', () => {
      const input = 'Hello {{name}}! Welcome to {{place}}.';
      const vars = extractVariableNames(input);
      expect(vars).toContain('name');
      expect(vars).toContain('place');
    });
  });

  describe('evaluateMessagePreview', () => {
    it('should evaluate ICU message with parameters', () => {
      const message = 'Hello {name}!';
      const preview = evaluateMessagePreview(
        message,
        { name: 'Alice' },
        'en',
        'icu'
      );
      expect(preview).toBe('Hello Alice!');
    });

    it('should evaluate ICU plural with numeric values', () => {
      const message =
        '{count, plural, =0 {No items} one {# item} other {# items}}';
      const zeroPreview = evaluateMessagePreview(
        message,
        { count: 0 },
        'en',
        'icu'
      );
      expect(zeroPreview).toBe('No items');

      const pluralPreview = evaluateMessagePreview(
        message,
        { count: 3 },
        'en',
        'icu'
      );
      expect(pluralPreview).toBe('3 items');
    });
  });
});
