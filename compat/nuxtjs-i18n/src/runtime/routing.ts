import { internationalization, routing } from '@intlayer/config/built';
import {
  getHTMLTextDir,
  getLocalizedUrl,
  getPathWithoutLocale,
} from '@intlayer/core/localization';
import { getCachedLocaleFromStorageClient } from '@intlayer/core/utils';
import type { LocalesValues } from '@intlayer/types/module_augmentation';
import { computed, getCurrentInstance, type Ref, ref } from 'vue';
import { createIntlayerClient } from 'vue-intlayer';
import type { Router } from 'vue-router';
import type {
  I18nHeadMetaInfo,
  I18nHeadOptions,
  LocalePathFunction,
  LocaleRouteFunction,
  LocalizedRoute,
  RouteBaseNameFunction,
  RouteLocationGeneric,
  Strategies,
  SwitchLocalePathFunction,
} from '../types';

export const defaultLocale = (internationalization?.defaultLocale ??
  'en') as string;
export const localeCodes = (internationalization?.locales ?? [
  defaultLocale,
]) as string[];

/** Separator of localized route names generated by `nuxt-intlayer`. */
const ROUTE_NAME_SEPARATOR = '___';

/** @nuxtjs/i18n strategy equivalent to intlayer's `routing.mode`. */
export const strategy: Strategies = (
  {
    'prefix-all': 'prefix',
    'prefix-no-default': 'prefix_except_default',
    'no-prefix': 'no_prefix',
    'search-params': 'no_prefix',
  } as const
)[routing?.mode ?? 'prefix-no-default'];

/** The active locale — intlayer's client singleton, readable anywhere. */
export const getActiveLocale = (): string =>
  (createIntlayerClient().locale.value as string | undefined) ?? defaultLocale;

/** The first browser language matching a configured locale. */
export const detectBrowserLocale = (): string | undefined =>
  typeof navigator === 'undefined'
    ? undefined
    : navigator.languages
        .map(
          (language) =>
            localeCodes.find((code) => code === language) ??
            localeCodes.find((code) => code === language.split('-')[0])
        )
        .find((code) => code !== undefined);

/** `useBrowserLocale()` — the browser locale among the configured ones. */
export const useBrowserLocale = (): string | null =>
  detectBrowserLocale() ?? null;

/** `useCookieLocale()` — the locale persisted by intlayer, or `''`. */
export const useCookieLocale = (): Ref<string> =>
  ref(getCachedLocaleFromStorageClient() ?? '');

/** The app router, when called from a component setup. */
export const getRouter = (): Router | undefined =>
  getCurrentInstance()?.appContext.config.globalProperties.$router as
    | Router
    | undefined;

/** Current URL path (`/fr/about?tab=1#top`), from the router or `window`. */
export const getCurrentFullPath = (router: Router | undefined): string => {
  if (router) return router.currentRoute.value.fullPath;
  if (typeof window === 'undefined') return '/';
  const { pathname, search, hash } = window.location;
  return `${pathname}${search}${hash}`;
};

const toSearch = (
  query: Exclude<RouteLocationGeneric, string>['query']
): string => {
  if (!query) return '';

  const searchParams = new URLSearchParams();
  for (const [key, value] of Object.entries(query)) {
    for (const item of Array.isArray(value) ? value : [value]) {
      searchParams.append(key, String(item));
    }
  }

  const search = searchParams.toString();
  return search ? `?${search}` : '';
};

/**
 * Serialises a route argument to a path with query and hash. A named route
 * is resolved through the router when one is available.
 */
const toFullPath = (
  route: RouteLocationGeneric,
  router: Router | undefined
): string => {
  if (typeof route === 'string') {
    return route.startsWith('/') ? route : `/${route}`;
  }

  if (!route.path && route.name && router?.hasRoute(route.name)) {
    return router.resolve({
      name: route.name,
      params: route.params,
      query: route.query,
      hash: route.hash,
    }).fullPath;
  }

  const path = route.path ?? `/${route.name ?? ''}`;
  const hash = route.hash
    ? route.hash.startsWith('#')
      ? route.hash
      : `#${route.hash}`
    : '';

  return `${path.startsWith('/') ? path : `/${path}`}${toSearch(route.query)}${hash}`;
};

/** Localizes a full path (query and hash kept) for `locale`. */
export const localizeFullPath = (fullPath: string, locale: string): string =>
  getLocalizedUrl(
    getPathWithoutLocale(fullPath),
    locale as LocalesValues
  ) as string;

/** `localePath(route, locale?)` bound to a router. */
export const createLocalePath =
  (router: Router | undefined): LocalePathFunction =>
  (route, locale) =>
    localizeFullPath(toFullPath(route, router), locale ?? getActiveLocale());

/** `switchLocalePath(locale)` bound to a router. */
export const createSwitchLocalePath =
  (router: Router | undefined): SwitchLocalePathFunction =>
  (locale) =>
    localizeFullPath(getCurrentFullPath(router), locale);

/** `localeRoute(route, locale?)` bound to a router. */
export const createLocaleRoute = (
  router: Router | undefined
): LocaleRouteFunction => {
  const localePath = createLocalePath(router);

  return (route, locale): LocalizedRoute => {
    const fullPath = localePath(route, locale);
    const path = fullPath.split(/[?#]/)[0] ?? fullPath;

    return typeof route === 'string'
      ? { path, fullPath }
      : { ...route, path, fullPath };
  };
};

/**
 * Route base name bound to a router: strips the locale from a route name
 * (`about___fr`) or path (`/fr/about`).
 */
export const createRouteBaseName =
  (router: Router | undefined): RouteBaseNameFunction =>
  (route) => {
    // A string without a leading slash is a route name, not a path.
    const name =
      typeof route === 'object'
        ? route.name
        : route && !route.startsWith('/')
          ? route
          : undefined;
    if (name) return name.split(ROUTE_NAME_SEPARATOR)[0];

    const path =
      typeof route === 'string'
        ? route
        : (route?.path ?? getCurrentFullPath(router));
    const basePath = getPathWithoutLocale(path.split(/[?#]/)[0] ?? path);

    return basePath.replace(/^\//, '') || 'index';
  };

/** `localePath(route, locale?)` — the localized path of a route. */
export const useLocalePath = (): LocalePathFunction =>
  createLocalePath(getRouter());

/** `switchLocalePath(locale)` — the current route in another locale. */
export const useSwitchLocalePath = (): SwitchLocalePathFunction =>
  createSwitchLocalePath(getRouter());

/** `localeRoute(route, locale?)` — a localized route object. */
export const useLocaleRoute = (): LocaleRouteFunction =>
  createLocaleRoute(getRouter());

/** `getRouteBaseName(route?)` — a route name without its locale suffix. */
export const useRouteBaseName = (): RouteBaseNameFunction =>
  createRouteBaseName(getRouter());

/** Resolves `html` attributes and SEO links for the active locale. */
const resolveLocaleHead = (
  { dir = true, lang = true, seo = true }: I18nHeadOptions,
  router: Router | undefined
): I18nHeadMetaInfo => {
  const activeLocale = getActiveLocale();
  const head: I18nHeadMetaInfo = {
    htmlAttrs: {
      ...(lang ? { lang: activeLocale } : {}),
      ...(dir ? { dir: getHTMLTextDir(activeLocale as LocalesValues) } : {}),
    },
  };

  if (!seo) return head;

  const basePath = getPathWithoutLocale(
    getCurrentFullPath(router).split(/[?#]/)[0] ?? '/'
  );

  head.link = [
    ...localeCodes.map((locale) => ({
      rel: 'alternate',
      hreflang: locale,
      href: localizeFullPath(basePath, locale),
    })),
    {
      rel: 'alternate',
      hreflang: 'x-default',
      href: localizeFullPath(basePath, defaultLocale),
    },
    {
      rel: 'canonical',
      href: localizeFullPath(basePath, activeLocale),
    },
  ];
  head.meta = [
    { property: 'og:locale', content: activeLocale },
    ...localeCodes
      .filter((locale) => locale !== activeLocale)
      .map((locale) => ({ property: 'og:locale:alternate', content: locale })),
  ];

  return head;
};

/** `useLocaleHead()` — reactive head attributes for the active locale. */
export const useLocaleHead = (
  options: I18nHeadOptions = {}
): Ref<I18nHeadMetaInfo> => {
  const router = getRouter();

  return computed(() => resolveLocaleHead(options, router));
};

/** Non-reactive head attributes, for `$localeHead()`. */
export const getLocaleHead = (
  options: I18nHeadOptions = {},
  router?: Router
): I18nHeadMetaInfo => resolveLocaleHead(options, router);
