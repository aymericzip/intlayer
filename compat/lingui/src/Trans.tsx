'use client';

import {
  parseTaggedMessage,
  type TaggedMessageToken,
} from '@intlayer/core/messageFormat';
import type { Dictionary } from '@intlayer/types/dictionary';
import type { I18n, MessageId } from '@lingui/core';
import type { I18nContext, TransProps, TransRenderProps } from '@lingui/react';
import {
  type ComponentType,
  Fragment,
  type ReactElement,
  type ReactNode,
  useContext,
} from 'react';
import { LinguiContext } from './LinguiContext';
import { useDictionary } from './useDictionary';
import {
  type DynamicDictionaryEntry,
  useDictionaryDynamic,
} from './useDictionaryDynamic';
import { useLingui } from './useLingui';

type RichRenderer = (...args: unknown[]) => ReactNode;

/** Maps tagged tokens to React nodes using a components record (numbered or named). */
const renderTaggedTokens = (
  tokens: TaggedMessageToken[],
  components: Record<
    string,
    ComponentType<Record<string, unknown>> | ReactElement | unknown
  >
): ReactNode[] =>
  tokens.map((token, tokenIndex) => {
    if (typeof token === 'string') return token;
    const children = renderTaggedTokens(token.children, components);
    const component = components[token.tag];
    if (component === undefined) {
      return <Fragment key={tokenIndex}>{children}</Fragment>;
    }
    if (typeof component === 'function') {
      return (
        <Fragment key={tokenIndex}>
          {(component as RichRenderer)(<>{children}</>)}
        </Fragment>
      );
    }
    if (
      typeof component === 'object' &&
      component !== null &&
      'type' in component
    ) {
      const { type: TagComponent, props: tagProps } = component as ReactElement;
      return (
        <TagComponent
          key={tokenIndex}
          {...(tagProps as Record<string, unknown>)}
        >
          {children}
        </TagComponent>
      );
    }
    return <Fragment key={tokenIndex}>{children}</Fragment>;
  });

/**
 * Renders a `<Trans>` element with the given `i18n` instance — shared by the
 * registry-backed component and its build-bound variants.
 */
const renderTrans = (
  {
    id,
    message,
    values,
    components,
    render,
    component: WrapperComponent,
  }: TransProps,
  i18n: I18n,
  DefaultComponent: I18nContext['defaultComponent']
): ReactElement | null => {
  const translation = i18n._(id as MessageId, values ?? {}, { message });
  const hasComponents = components && Object.keys(components).length > 0;

  let content: ReactNode;

  if (hasComponents) {
    const tokens = parseTaggedMessage(translation);
    const nodes = renderTaggedTokens(tokens, components);
    content = <>{nodes}</>;
  } else {
    content = translation;
  }

  const renderProps: TransRenderProps = {
    id: id as MessageId,
    translation: content,
    children: content,
    message: message ?? null,
  };

  if (typeof render === 'function') {
    return render(renderProps);
  }

  const Wrapper =
    WrapperComponent ??
    (DefaultComponent as ComponentType<TransRenderProps> | undefined);

  if (Wrapper) {
    return <Wrapper {...renderProps}>{content}</Wrapper>;
  }

  return <>{content}</>;
};

/**
 * Drop-in for `@lingui/react`'s `<Trans>`.
 *
 * Looks up the message `id` in the intlayer dictionaries and renders the
 * result. When `components` is provided, named tags in the translated string
 * are mapped to React elements (uses `parseTaggedMessage` from
 * `@intlayer/core`).
 *
 * @example
 * ```tsx
 * // Simple message
 * <Trans id="home.title" message="Welcome" />
 *
 * // Rich text with components
 * <Trans
 *   id="legal.terms"
 *   message="I agree to the <link>terms</link>"
 *   components={{ link: <a href="/terms" /> }}
 * />
 * ```
 */
export const Trans = (props: TransProps): ReactElement | null => {
  const { i18n, defaultComponent } = useLingui();

  return renderTrans(props, i18n, defaultComponent);
};

/**
 * Dictionary-accepting variant of `<Trans>`.
 *
 * Used internally by the build-time optimization: the babel plugin reads the
 * dictionary named by the element's `id`, pre-imports it and passes it here,
 * so the element resolves without the runtime registry.
 *
 * @example (generated by the plugin, not written manually)
 * import _hero from '.intlayer/dictionaries/hero.json' with { type: 'json' };
 * <TransDictionary id="hero.title" dictionary={_hero} />
 */
export const TransDictionary = ({
  dictionary,
  ...props
}: TransProps & { dictionary: Dictionary }): ReactElement | null => {
  const { i18n } = useDictionary(dictionary);
  const { defaultComponent } = useContext(LinguiContext) ?? {};

  return renderTrans(props, i18n, defaultComponent);
};

/**
 * Dynamic dictionary-accepting variant of `<Trans>` — the counterpart of
 * {@link TransDictionary} for dictionaries imported lazily per locale.
 *
 * @example (generated by the plugin, not written manually)
 * import _hero from '.intlayer/dynamic_dictionaries/hero.mjs';
 * <TransDictionaryDynamic id="hero.title" dictionary={[_hero, 'hero']} />
 */
export const TransDictionaryDynamic = ({
  dictionary,
  ...props
}: TransProps & {
  dictionary: DynamicDictionaryEntry;
}): ReactElement | null => {
  const { i18n } = useDictionaryDynamic(dictionary);
  const { defaultComponent } = useContext(LinguiContext) ?? {};

  return renderTrans(props, i18n, defaultComponent);
};
