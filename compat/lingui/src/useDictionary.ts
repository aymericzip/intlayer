'use client';

import type { Dictionary } from '@intlayer/types/dictionary';
import type { LocalesValues } from '@intlayer/types/module_augmentation';
import type { I18nContext } from '@lingui/react';
import { useMemo } from 'react';
import { getDictionary, useLocale } from 'react-intlayer';
import { I18nClass } from './I18nClass';

/**
 * Builds the `useLingui()` result around an `I18nClass` bound to interpreted
 * dictionary content. Shared by the static and dynamic optimized variants.
 *
 * @internal
 */
export const createBoundLinguiContext = (
  locale: string,
  dictionaries: Record<string, unknown>
): I18nContext => {
  const instance = new I18nClass({ locale }).bindDictionaries(dictionaries);

  return {
    i18n: instance as unknown as I18nContext['i18n'],
    _: instance._.bind(instance) as I18nContext['_'],
  } as I18nContext;
};

/**
 * Dictionary-accepting variant of `useLingui`.
 *
 * Used internally by the build-time optimization: `useLingui()` names no
 * dictionary, so the babel plugin collects the first segment of every message
 * id used in the file, pre-imports those dictionaries at build time and passes
 * them all here. Lookups then never reach the runtime registry, which keeps
 * every other dictionary out of the chunk.
 *
 * @example (generated by the plugin, not written manually)
 * import _footer from '.intlayer/dictionaries/footer.json' with { type: 'json' };
 * import _hero from '.intlayer/dictionaries/hero.json' with { type: 'json' };
 * const { i18n } = useDictionary(_footer, _hero);
 * i18n._('footer.github');
 */
export const useDictionary = (...dictionaries: Dictionary[]): I18nContext => {
  const { locale } = useLocale();

  // The dictionaries are module-level JSON imports, so their keys identify the
  // call site's binding without depending on a variable-length array.
  const dictionaryKeysIdentity = dictionaries
    .map((dictionary) => dictionary.key)
    .join('\0');

  return useMemo(
    () =>
      createBoundLinguiContext(
        locale as string,
        Object.fromEntries(
          dictionaries.map((dictionary) => [
            dictionary.key,
            getDictionary(dictionary, locale as LocalesValues),
          ])
        )
      ),
    [locale, dictionaryKeysIdentity]
  );
};
