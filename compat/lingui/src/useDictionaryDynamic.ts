'use client';

import { internationalization } from '@intlayer/config/built';
import { getPreloadedDictionary } from '@intlayer/core/dictionaryManipulator';
import type { Dictionary } from '@intlayer/types/dictionary';
import type {
  LocalesValues,
  StrictModeLocaleMap,
} from '@intlayer/types/module_augmentation';
import type { I18nContext } from '@lingui/react';
import { useMemo } from 'react';
// `useLoadDynamic` is a suspender cache, not a React hook — aliased to a
// non-hook name so it can be invoked once per bound dictionary.
import {
  getDictionary,
  useLoadDynamic as loadDynamicChunk,
  useLocale,
} from 'react-intlayer';
import { createBoundLinguiContext } from './useDictionary';

/** One dictionary to load lazily: its per-locale loader map and its key. */
export type DynamicDictionaryEntry = [
  loaders: StrictModeLocaleMap<() => Promise<Dictionary>>,
  key: string,
];

/**
 * Reads one lazily-loaded dictionary for `locale`, suspending until its chunk
 * is available. Mirrors `react-intlayer`'s `useDictionaryDynamic` for plain
 * locale → loader maps, including the chunk a build-tool plugin may already
 * have started while the entry point was evaluating.
 */
const readDynamicDictionary = (
  [loaders, key]: DynamicDictionaryEntry,
  locale: LocalesValues
): unknown => {
  const dictionary =
    getPreloadedDictionary(loaders, locale) ??
    loadDynamicChunk<Dictionary>(
      `${key}.${locale}`,
      loaders[locale as keyof typeof loaders]?.() as Promise<Dictionary>
    );

  return getDictionary(dictionary, locale);
};

/**
 * Dynamic dictionary-accepting variant of `useLingui`.
 *
 * Counterpart to {@link useDictionary} for dictionaries imported lazily per
 * locale. Used internally by the build-time optimization.
 *
 * @example (generated by the plugin, not written manually)
 * import _footer from '.intlayer/dynamic_dictionaries/footer.mjs';
 * const { i18n } = useDictionaryDynamic([_footer, 'footer']);
 */
export const useDictionaryDynamic = (
  ...entries: DynamicDictionaryEntry[]
): I18nContext => {
  const { locale } = useLocale();
  const localeTarget = (locale ??
    internationalization.defaultLocale) as LocalesValues;

  // The entry list is emitted by the build for one call site, so its keys
  // identify the binding without depending on a variable-length array.
  const dictionaryKeysIdentity = entries.map(([, key]) => key).join('\0');

  return useMemo(
    () =>
      createBoundLinguiContext(
        localeTarget,
        Object.fromEntries(
          entries.map((entry) => [
            entry[1],
            readDynamicDictionary(entry, localeTarget),
          ])
        )
      ),
    [localeTarget, dictionaryKeysIdentity]
  );
};
